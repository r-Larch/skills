using System.Text;
using WorkState.Import.Model;

namespace WorkState.Import;

/// <summary>
/// The parse-failure report. It is the deliverable as much as the rows are (brief §3): every shape the
/// importer could not type is a thing the schema cannot yet express, and the list has to arrive before
/// anything is built on the assumption that it can.
/// </summary>
public static class ImportReport
{
    public static string Render(
        ImportOutcome outcome,
        IReadOnlyDictionary<string, string> judgements,
        string? doubts = null)
    {
        var report = new StringBuilder();

        report.AppendLine("# Import report — the real corpus in the store");
        report.AppendLine();
        report.AppendLine(
            "> Generated by `tools/WorkState.Import`. Re-run it and this file is rewritten from the run,");
        report.AppendLine("> so nothing here is maintained by hand — including the judgements, which live in");
        report.AppendLine("> `Judgements.cs`.");
        report.AppendLine();

        if (doubts is not null)
        {
            report.AppendLine(doubts);
            report.AppendLine();
        }

        report.AppendLine("## Totals");
        report.AppendLine();
        report.AppendLine("| | |");
        report.AppendLine("|---|---|");
        report.AppendLine($"| Runs | {outcome.Runs.Count} |");
        report.AppendLine($"| Markdown files imported | {outcome.Files} |");
        report.AppendLine($"| Files referenced, not imported (spec + measurement output) | {outcome.FilesSkipped} |");
        report.AppendLine($"| Docs | {outcome.Docs} |");
        report.AppendLine($"| Doc blocks (verbatim) | {outcome.Blocks} |");
        report.AppendLine($"| Items | {outcome.Items} |");
        report.AppendLine($"| Assumptions | {outcome.Assumptions} |");
        report.AppendLine($"| Notes | {outcome.Notes} |");
        report.AppendLine($"| Constraint rules | {outcome.Constraints} |");
        report.AppendLine($"| Verifications | {outcome.Verifications} |");
        report.AppendLine($"| Artifacts | {outcome.Artifacts} |");
        report.AppendLine($"| Attempts (briefs as issued) | {outcome.Attempts} |");
        report.AppendLine($"| Events | {outcome.Events} |");
        report.AppendLine($"| U+FFFD in imported text | {outcome.ReplacementChars} |");
        report.AppendLine($"| Control characters removed to make text storable | {outcome.ControlChars} |");
        report.AppendLine();

        report.AppendLine("## Per run");
        report.AppendLine();
        report.AppendLine("| project | run | files | blocks | items | assumptions | notes | rules | verifications |");
        report.AppendLine("|---|---|---|---:|---:|---:|---:|---:|---:|");
        foreach (var run in outcome.Runs.OrderBy(r => r.Project, StringComparer.Ordinal).ThenBy(r => r.Run, StringComparer.Ordinal))
        {
            report.AppendLine(
                $"| {run.Project} | {run.Run} | {run.Files} | {run.Blocks} | {run.Items} | " +
                $"{run.Assumptions} | {run.Notes} | {run.Constraints} | {run.Verifications} |");
        }

        report.AppendLine();
        report.AppendLine("## Unmapped shapes, worst first");
        report.AppendLine();
        report.AppendLine(
            "Each of these landed in a `doc_block` verbatim and was counted here. Nothing was dropped.");
        report.AppendLine();

        var groups = outcome.Unmapped.Shapes
            .GroupBy(s => s.Category)
            .OrderByDescending(g => g.Sum(s => s.Count))
            .ToList();

        foreach (var group in groups)
        {
            var total = group.Sum(s => s.Count);
            report.AppendLine($"### `{group.Key}` — {total} occurrence(s) across {group.SelectMany(s => s.Files).Distinct().Count()} file(s)");
            report.AppendLine();

            if (judgements.TryGetValue(group.Key, out var judgement))
            {
                report.AppendLine($"**Judgement.** {judgement}");
                report.AppendLine();
            }

            report.AppendLine("| n | shape | example |");
            report.AppendLine("|---:|---|---|");

            foreach (var shape in group.OrderByDescending(s => s.Count).Take(20))
            {
                report.AppendLine($"| {shape.Count} | {Escape(shape.Shape)} | {Escape(shape.Sample)} |");
            }

            var remainder = group.Count() - 20;
            if (remainder > 0)
            {
                report.AppendLine($"| | *…and {remainder} further shape(s) in this category* | |");
            }

            report.AppendLine();
        }

        return report.ToString();
    }

    private static string Escape(string value)
        => value.Replace("|", "\\|", StringComparison.Ordinal)
            .Replace("\n", " ", StringComparison.Ordinal)
            .Trim();
}
